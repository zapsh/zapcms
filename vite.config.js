import { defineConfig } from 'vite';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = dirname(fileURLToPath(import.meta.url));

/**
 * 打包时移除「只有 SCSS 入口」产生的空 JS 占位文件。
 */
function dropEmptyJs() {
  return {
    name: 'zapcms-drop-empty-js',
    generateBundle(_options, bundle) {
      for (const [fileName, output] of Object.entries(bundle)) {
        if (output.type === 'chunk' && output.code.trim() === '') {
          delete bundle[fileName];
        }
      }
    },
  };
}

/**
 * 在构建产出的 CSS 顶部写入「勿直接修改」提示（@charset 必须保持在第一行）。
 */
function cssBanner(banner) {
  return {
    name: 'zapcms-css-banner',
    generateBundle(_options, bundle) {
      for (const output of Object.values(bundle)) {
        if (output.type !== 'asset' || !output.fileName.endsWith('.css')) continue;
        const source = String(output.source);
        const charset = '@charset "UTF-8";';
        output.source = source.startsWith(charset)
          ? charset + banner + source.slice(charset.length)
          : banner + source;
      }
    },
  };
}

export default defineConfig({
  root,
  build: {
    outDir: resolve(root, 'assets/admin'),
    // 输出目录中还包含手工维护的 admin.js / zap-admin.js / 图片，禁止清空
    emptyOutDir: false,
    // 生成 .vite/manifest.json，供 PHP 侧解析带 hash 的产物文件名
    manifest: true,
    cssCodeSplit: true,
    target: 'es2020',
    rollupOptions: {
      input: {
        // 后台主样式（Bootstrap + AdminLTE + ZAP 定制）
        'zap-admin': resolve(root, 'resources/admin/scss/zap-admin.scss'),
        // 安装向导使用的最小 Bootstrap 样式
        bootstrap: resolve(root, 'resources/admin/scss/bootstrap.scss'),
        // Bootstrap JS（暴露 window.bootstrap 供 admin.js 使用）
        'bootstrap.bundle': resolve(root, 'resources/admin/js/bootstrap.js'),
        // 代码编辑器（CodeMirror 6，按需加载；语言包自动分包）
        editor: resolve(root, 'resources/admin/js/editor.js'),
      },
      output: {
        // 文件名带 hash：内容变化即产生新文件名，可安全地设置长期缓存
        entryFileNames: 'js/[name]-[hash].js',
        assetFileNames: 'css/[name]-[hash][extname]',
        // 动态 import 产生的 chunk（CodeMirror 语言包）：按包名命名并带 hash
        chunkFileNames(chunkInfo) {
          const ids = chunkInfo.moduleIds || [];
          const lang = ids.map((id) => id.match(/@codemirror[\\/]lang-([a-z0-9]+)[\\/]/i)).find(Boolean);
          if (lang) return `js/cm-lang-${lang[1].toLowerCase()}-[hash].js`;

          const lezer = ids.map((id) => id.match(/@lezer[\\/]([a-z0-9-]+)[\\/]/i)).find(Boolean);
          if (lezer) return `js/cm-lang-${lezer[1].toLowerCase()}-[hash].js`;

          return 'js/cm-chunk-[hash].js';
        },
      },
      plugins: [
        dropEmptyJs(),
        cssBanner('/*! Built by Vite from resources/admin - do not edit this file directly. */'),
      ],
    },
  },
  css: {
    preprocessorOptions: {
      scss: {
        // 允许 @import "bootstrap/scss/..." 这类裸模块路径
        loadPaths: [resolve(root, 'node_modules')],
        // Bootstrap 5.3 仍在使用 @import / 旧版 if() 等语法，这里统一静音其弃用告警
        // 注意：sass 1.10x 起 mixed-decls 已失效，不能再列入（会反向告警）
        silenceDeprecations: ['import', 'global-builtin', 'color-functions', 'abs-percent', 'if-function'],
      },
    },
  },
});
