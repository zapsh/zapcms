 * 命令行一键安装 ZapCMS：
 *   1. 写入应用密钥 config.php (app_key) 与数据库连接 database.php
 *   2. 建立全部数据表（CreateTables，若已存在则重建）
 *   3. 写入基础数据（CreateBaseData，含管理员/演示账号、菜单、栏目、演示内容、迁移记录）
 *   4. 可选覆盖管理员(admin)密码 / 邮箱
 *
 *   php console zapcms:Install                              # 用现有配置安装（或全新库）
 *   php console zapcms:Install -f                            # 重建全部表并重装（危险：清空现有数据）
 *
 *   # 指定数据库连接（写入 database.php），MySQL 示例：
 *   php console zapcms:Install --db-type mysql --db-host 127.0.0.1 --db-port 3306 \
 *       --db-name zapcms --db-user root --db-pass root --db-prefix zap_
 *   # 简写：
 *   php console zapcms:Install -t mysql -d zapcms -u root -p root
 *
 *   # SQLite 示例：
 *   php console zapcms:Install --db-type sqlite
 *
 *   # 指定应用密钥 / 管理员：
 *   php console zapcms:Install --app-key <64hex> -a '你的密码' -e admin@example.com
 *
 * 说明：CreateBaseData::install() 已包含 migrations 种子记录（id 24/25），
 *       安装后 Migrator 不会重复执行这些迁移，与「CreateSchema -b」全新安装语义一致。
 *       如需 public/ 部署模式，安装完成后另跑：php console zapcms:MakePublic
 */

namespace zapcms\commands;

use zapcms\support\CreateBaseData;
use zapcms\support\CreateTables;
use zap\console\Command;
use zap\console\Input;
use zap\console\Output;
use zap\db\Schema;
use zap\DB;

class Install extends Command
{
    public function configure(): void
    {
        $this->setName('zapcms:Install')
             ->setDescription('命令行一键安装 ZapCMS（写入配置 + 建表 + 写入基础数据）');

        $this->addOption('db-type',   't', '数据库类型：mysql | sqlite（默认 mysql）');
        $this->addOption('db-host',   '',  'MySQL 主机（默认 127.0.0.1）');
        $this->addOption('db-port',   '',  'MySQL 端口（默认 3306）');
        $this->addOption('db-name',   'd', 'MySQL 数据库名（mysql 必填）');
        $this->addOption('db-user',   'u', 'MySQL 用户名（默认 root）');
        $this->addOption('db-pass',   'p', 'MySQL 密码');
        $this->addOption('db-prefix', '',  '表前缀（默认 zap_）');
        $this->addOption('app-key',   'k', '应用加密密钥（64 位 hex；不填则在为空时自动生成）');
        $this->addOption('admin-password', 'a', '管理员(admin)登录密码');
        $this->addOption('admin-email',    'e', '管理员邮箱');
        $this->addOption('force',     'f', '重建全部数据表并重装（危险：清空现有数据）');
    }

    public function execute(Input $input, Output $output): int
    {
        $force      = $this->flag($input, ['force', 'f']);
        $adminPass  = $this->opt($input, 'admin-password', 'a');
        $adminEmail = $this->opt($input, 'admin-email', 'e');
        $appKey     = $this->opt($input, 'app-key', 'k');

        // 是否提供了任一数据库参数（决定是否重写 database.php）
        $writeDb = $this->flag($input, ['db-type', 't', 'db-name', 'd', 'db-host', 'db-user', 'u', 'db-pass', 'p', 'db-port', 'db-prefix']);

        // ── 1) 数据库参数校验 + 必要时建库 ──
        $dbType = 'mysql';
        if ($writeDb) {
            $dbType = strtolower((string) ($this->opt($input, 'db-type', 't') ?? 'mysql'));
            $dbHost = $this->opt($input, 'db-host') ?? '127.0.0.1';
            $dbPort = $this->opt($input, 'db-port') ?? '3306';
            $dbName = $this->opt($input, 'db-name', 'd') ?? 'zapcms';
            $dbUser = $this->opt($input, 'db-user', 'u') ?? 'root';
            $dbPass = $this->opt($input, 'db-pass', 'p') ?? '';
            $dbPrefix = $this->opt($input, 'db-prefix') ?? 'zap_';

            $output->writeln("校验数据库连接（driver={$dbType}）...");
            if ($dbType === 'sqlite') {
                try {
                    $dsn = sprintf('sqlite:%s', var_path('data/zapcms.db'));
                    new \PDO($dsn);
                } catch (\Throwable $e) {
                    $output->error('SQLite 连接失败：' . $e->getMessage());
                    return self::FAILURE;
                }
            } else {
                if (!$this->checkMysql($output, $dbHost, (int) $dbPort, $dbName, $dbUser, $dbPass)) {
                    return self::FAILURE;
                }
            }
        }

        // ── 2) 写入 app_key（config.php） ──
        $this->writeAppKey($output, $appKey);

        // ── 3) 写入 database.php ──
        if ($writeDb) {
            $connections = $this->buildDatabaseConfig($dbType, $dbHost ?? '127.0.0.1', $dbPort ?? '3306', $dbName ?? 'zapcms', $dbUser ?? 'root', $dbPass ?? '', $dbPrefix ?? 'zap_');
            $content = "<?php\n\n// Automatically generated by zapcms:Install\n"
                . "// Date: " . date('Y-m-d H:i:s') . "\nreturn "
                . var_export(['default' => 'default', 'connections' => $connections], true) . ";\n";
            file_put_contents(config_path('database.php'), $content);
            $output->writeln("<info>已写入数据库配置 database.php（driver={$dbType}）。</info>");
        }

        // ── 4) 重载配置 + 重置 DB 连接缓存（让后续建表使用新配置） ──
        if ($writeDb || $appKey !== null) {
            config_clear();
            $this->resetDbConnections();
        }

        // ── 5) 数据库连接检查（使用最终生效的配置） ──
        $output->writeln('检查数据库连接...');
        try {
            DB::getPDO();
        } catch (\Throwable $e) {
            $output->error('数据库连接失败：' . $e->getMessage());
            $output->writeln('请检查 database.php 配置；MySQL 请确认已先创建数据库。');
            return self::FAILURE;
        }

        // ── 6) 是否已安装（migrations 表有记录即视为已安装） ──
        $installed = false;
        try {
            $row = DB::fetch("SELECT COUNT(*) AS c FROM {migrations}");
            $installed = (int) ($row['c'] ?? 0) > 0;
        } catch (\Throwable $e) {
            $installed = false;
        }

        if ($installed && !$force) {
            $output->writeln('<error>检测到 ZapCMS 已安装（migrations 表非空）。</error>');
            $output->writeln('如需重建全部数据表并重新安装，请追加 -f 参数（会清空现有所有数据）：');
            $output->writeln('  php console zapcms:Install -f');
            return self::FAILURE;
        }

        if ($installed && $force) {
            $output->writeln('<warning>已检测到已安装数据，-f 将重建全部数据表（清空现有数据），请确认已备份。</warning>');
        }

        // ── 7) 建表（对已有表先 dropIfExists 再 create，幂等安全） ──
        $output->writeln('正在创建数据表（已存在的表将被重建）...');
        Schema::setOutput($output);
        (new CreateTables())->createSchema();
        $output->writeln('<info>数据表创建完成。</info>');

        // ── 8) 写入基础数据 ──
        $output->writeln('正在写入基础数据（管理员、菜单、栏目、演示内容）...');
        $overrides = [];
        if ($adminPass !== null && $adminPass !== '') {
            // 种子密码为 bcrypt，登录端使用 password_verify，故此处同样用 bcrypt 生成
            $overrides['passwords']['admin'] = password_hash((string) $adminPass, PASSWORD_BCRYPT);
        }
        CreateBaseData::install($overrides);
        $output->writeln('<info>基础数据写入完成。</info>');

        // ── 9) 覆盖管理员邮箱 ──
        if ($adminEmail !== null && $adminEmail !== '') {
            DB::update('admin', ['email' => (string) $adminEmail], ['username' => 'admin']);
            $output->writeln('管理员邮箱已更新为：' . $adminEmail);
        }

        // ── 10) 完成提示 ──
        $output->writeln('');
        $output->writeln('<success>ZapCMS 安装完成！</success>');
        $output->writeln('后台账号：admin（管理员） / demo（演示）');
        if ($adminPass !== null && $adminPass !== '') {
            $output->writeln('管理员(admin)密码已设置为你指定的密码。');
        } else {
            $output->writeln('未指定密码，admin 使用种子默认密码，请尽快在后台修改。');
        }
        $output->writeln('');
        $output->writeln('下一步：');
        $output->writeln('  - 访问后台开始使用；');
        $output->writeln('  - 如需 public/ 部署模式，运行：php console zapcms:MakePublic');

        return self::SUCCESS;
    }

    /**
     * 校验 MySQL 连接，并在库不存在时尝试创建（CREATE DATABASE IF NOT EXISTS）。
     */
    private function checkMysql(Output $output, string $host, int $port, string $dbName, string $user, string $pass): bool
    {
        try {
            $dsn = "mysql:host={$host};port={$port};charset=utf8";
            $pdo = new \PDO($dsn, $user, $pass, [\PDO::ATTR_ERRMODE => \PDO::ERRMODE_EXCEPTION]);
        } catch (\Throwable $e) {
            $output->error("MySQL 连接失败（host={$host};port={$port}）：" . $e->getMessage());
            $output->writeln('请确认 MySQL 服务已启动、用户名/密码正确且有权限。');
            return false;
        }

        try {
            $pdo->exec("CREATE DATABASE IF NOT EXISTS `{$dbName}` CHARACTER SET utf8 COLLATE utf8_unicode_ci");
            $output->writeln("<info>数据库 `{$dbName}` 已就绪（不存在则已创建）。</info>");
        } catch (\Throwable $e) {
            $output->error("无法创建/选择数据库 `{$dbName}`：" . $e->getMessage());
            $output->writeln('请手动创建该数据库后重试，或确认账号有建库权限。');
            return false;
        }

        return true;
    }

    /**
     * 写入/生成 config.php 的 app_key（保留其余配置与注释）。
     */
    private function writeAppKey(Output $output, ?string $appKey): void
    {
        $configFile = config_path('config.php');
        $content = (string) file_get_contents($configFile);

        $existing = '';
        if (preg_match('/"app_key"\s*=>\s*"([^"]*)"/', $content, $m)) {
            $existing = $m[1];
        }

        if ($appKey !== null && $appKey !== '') {
            if (!preg_match('/^[0-9a-fA-F]{64}$/', $appKey)) {
                $output->error('app-key 必须是 64 位十六进制字符串，已跳过写入（保留现有配置）。');
                return;
            }
            $newKey = strtolower($appKey);
        } elseif ($existing === '') {
            $newKey = bin2hex(random_bytes(32));
        } else {
            // 已存在且未指定 -> 保留
            return;
        }

        $content = preg_replace('/("app_key"\s*=>\s*")[^"]*(")/', '$1' . $newKey . '$2', $content);
        file_put_contents($configFile, $content);
        $output->writeln('<info>已写入应用密钥 app_key（config.php）。</info>');
    }

    /**
     * 构造 database.php 的 connections 数组（与 database.sample.php 结构一致）。
     */
    private function buildDatabaseConfig(string $type, string $host, string $port, string $name, string $user, string $pass, string $prefix): array
    {
        if ($type === 'sqlite') {
            return [
                'default' => [
                    'driver' => 'sqlite',
                    'prefix' => $prefix !== '' ? $prefix : 'zap_',
                    'dsn'    => sprintf('sqlite:%s', var_path('data/zapcms.db')),
                ],
            ];
        }

        return [
            'default' => [
                'driver'   => 'mysql',
                'host'     => $host,
                'port'     => (int) $port,
                'dbname'   => $name,
                'username' => $user,
                'password' => $pass,
                'charset'  => 'utf8',
                'collate'  => 'utf8_unicode_ci',
                'prefix'   => $prefix,
                'options'  => [],
            ],
        ];
    }

    /**
     * 重置框架 DB 连接缓存，使其基于（已写入的）新配置重新建立连接。
     */
    private function resetDbConnections(): void
    {
        $ref = new \ReflectionClass(DB::class);
        foreach (['connections', 'transactionConnection'] as $propName) {
            $prop = $ref->getProperty($propName);
            $prop->setAccessible(true);
            $prop->setValue($propName === 'connections' ? [] : null);
        }
    }

    private function opt(Input $input, string $long, string $short = ''): ?string
    {
        $v = $input->getParam($long);
        if ($v === null && $short !== '') {
            $v = $input->getParam($short);
        }
        return is_string($v) ? $v : null;
    }

    /**
     * 判断短选项 / 长选项 / 位置参数是否存在。
     */
    protected static function flag(Input $input, array $names): bool
    {
        foreach ($names as $name) {
            if ($input->getOption($name) || $input->hasParam($name)) {
                return true;
            }
        }

        return false;
    }

    public function help(): int
    {
        $this->out->writeln('ZapCMS 命令行安装');
        $this->out->writeln('Help:');
        $this->out->writeln('-t/--db-type        数据库类型 mysql|sqlite（默认 mysql）');
        $this->out->writeln('-d/--db-name        MySQL 数据库名');
        $this->out->writeln('-u/--db-user        MySQL 用户名（默认 root）');
        $this->out->writeln('-p/--db-pass        MySQL 密码');
        $this->out->writeln('    --db-host       MySQL 主机（默认 127.0.0.1）');
        $this->out->writeln('    --db-port       MySQL 端口（默认 3306）');
        $this->out->writeln('    --db-prefix     表前缀（默认 zap_）');
        $this->out->writeln('-k/--app-key        应用密钥 64 位 hex（留空则自动生成）');
        $this->out->writeln('-a/--admin-password 管理员(admin)密码');
        $this->out->writeln('-e/--admin-email    管理员邮箱');
        $this->out->writeln('-f/--force          重建全部数据表并重装（危险）');
        $this->out->writeln('');
        $this->out->writeln('Usage:');
        $this->out->writeln('  php console zapcms:Install');
        $this->out->writeln('  php console zapcms:Install -t mysql -d zapcms -u root -p root');
        $this->out->writeln('  php console zapcms:Install -t sqlite');
        $this->out->writeln("  php console zapcms:Install -a 'your-password' -e admin@example.com");
        return self::SUCCESS;
    }
}
