namespace zapcms\support;

class ZapConfig
{
    /**
     * 生成数据库配置文件 config/database.php。
     *
     *
     * @param array  $data 数据库配置（通常来自 config('database')）
     * @param string $file 目标配置文件路径
     */
    public static function createConfig($data, $file)
    {
        $isSqlite = ($data['connections']['default']['driver'] ?? null) === 'sqlite';
        $sentinel = '__ZAP_SQLITE_DSN__';

        if ($isSqlite) {
            $data['connections']['default']['dsn'] = $sentinel;
        }

        $conf  = "<?php\n\n// Automatically generated by zapcms\n";
        $conf .= '// Date: ' . date(Z_DATE_TIME) . "\n";
        $conf .= "return ";
        $conf .= zap_var_export($data, true);
        $conf .= ";\n";

        if ($isSqlite) {
            $dbpath = config('db.dbpath');
            $conf = str_replace(
                ["'{$sentinel}'", "\"{$sentinel}\""],
                'sprintf("sqlite:%s", var_path("' . $dbpath . '"))',
                $conf
            );
        }

        return file_put_contents($file, $conf);
    }
}